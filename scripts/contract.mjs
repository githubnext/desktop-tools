#!/usr/bin/env node
// Writes src/contract.ts, what the npm package's /tools and /protocol export, from the tool declarations in
// native2/Sources/DesktopProtocol/ContractTools.swift: it builds desktop-tools-mcp and runs it with --contract.
// With --check, fails when src/contract.ts differs. --scratch <dir> is SwiftPM's scratch path.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const { values } = parseArgs({ options: { check: { type: "boolean" }, scratch: { type: "string" } }, strict: true });
const root = fileURLToPath(new URL("..", import.meta.url));
const scratch = values.scratch ?? join(root, "native2", ".build");
const file = join(root, "src", "contract.ts");

const swift = ["--package-path", join(root, "native2"), "--scratch-path", scratch];
execFileSync("swift", ["build", ...swift, "--product", "desktop-tools-mcp"], { stdio: ["ignore", "ignore", "inherit"] });
const bin = execFileSync("swift", ["build", ...swift, "--show-bin-path"], { encoding: "utf8" }).trim();
const contract = JSON.parse(execFileSync(join(bin, "desktop-tools-mcp"), ["--contract"], { encoding: "utf8" }));

const text = `// Generated by scripts/contract.mjs from native2/Sources/DesktopProtocol/ContractTools.swift; don't edit.
// {{place}} and {{app}} stand for where the tools act and the app that holds the permissions.

export const contract = ${JSON.stringify(contract, null, "\t")} as const;
`;
if (values.check) {
	let current = "";
	try { current = readFileSync(file, "utf8"); } catch {}
	if (current !== text) {
		console.error("src/contract.ts is stale; run npm run contract");
		process.exit(1);
	}
} else writeFileSync(file, text);
