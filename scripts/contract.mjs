#!/usr/bin/env node
// Writes the MCP contract the Swift server (native2, #143) must serve, from today's Node server: its
// instructions and tools/list, compiled into the Swift code so no resource bundle has to travel with an embedded host.
// With --check, fails when they differ, so the TS definitions stay the source. It runs the server with --wire 2, so the
// text native2 owns (desktopTools and desktopToolRules with wire 2) is what it serves, and embedders on wire 2 get it too.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const file = new URL("../native2/Sources/DesktopProtocol/ContractText.swift", import.meta.url);
const input = [
	{ jsonrpc: "2.0", id: 1, method: "initialize", params: { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "contract" } } },
	{ jsonrpc: "2.0", id: 2, method: "tools/list" },
].map((m) => JSON.stringify(m)).join("\n") + "\n";
const out = execFileSync(process.execPath, [new URL("../dist/mcp.js", import.meta.url).pathname, "--wire", "2"], { input, encoding: "utf8" });
const [init, list] = out.trim().split("\n").map((line) => JSON.parse(line).result);

const raw = (text) => {
	if (text.includes('"""##')) throw new Error("The contract contains the raw string delimiter.");
	return `##"""\n${text}\n"""##`;
};
const text = `// Generated by scripts/contract.mjs from the Node server; don't edit.

extension Contract {
	static let instructionsText = ${raw(init.instructions)}

	static let toolsText = ${raw(JSON.stringify(list.tools, null, "\t"))}
}
`;
if (process.argv.includes("--check")) {
	let current = "";
	try { current = readFileSync(file, "utf8"); } catch {}
	if (current !== text) {
		console.error("native2/Sources/DesktopProtocol/ContractText.swift is stale; run node scripts/contract.mjs");
		process.exit(1);
	}
} else writeFileSync(file, text);
